"""Builds modules/custom/lua/bots_trade_names.lua: [item id] = shout name, for every item bots_craft_data.lua prices.
Crafted results keep their recipe name; everything else gets item_basic.sql's sort name, title-cased.
Run:  python build_trade_names.py --server C:\\ffxi-local\\server"""
import argparse, os, re

SMALL = {"of", "the", "and", "a", "an", "in", "on", "to"}
ROMAN = {"ii", "iii", "iv", "v", "vi", "vii", "viii", "ix", "x", "hq", "nq"}


def nice(sort):
    words = sort.replace("_", " ").split()
    out = []
    for i, w in enumerate(words):
        if w in ROMAN:
            out.append(w.upper())
        elif i > 0 and w in SMALL:
            out.append(w)
        else:
            out.append("-".join(p[:1].upper() + p[1:] for p in w.split("-")))
    return " ".join(out)


def lua_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", default=r"C:\ffxi-local\server")
    a = ap.parse_args()
    lua = os.path.join(a.server, "modules", "custom", "lua")
    data = open(os.path.join(lua, "bots_craft_data.lua"), encoding="utf-8").read()
    names = {}
    for m in re.finditer(r"\{ \d+, \d+, \d+, \{[^}]*\}, (\d+), \d+, '((?:[^'\\]|\\.)*)' \}", data):
        names[int(m.group(1))] = m.group(2).replace("\\'", "'")
    items = data[data.index("d.items"):]
    ids = [int(x) for x in re.findall(r"\[(\d+)\] = \{", items)]
    basic = {}
    rx = re.compile(r"INSERT INTO `item_basic` VALUES \((\d+),\d+,'(?:[^'\\]|\\.)*','((?:[^'\\]|\\.)*)'")
    for line in open(os.path.join(a.server, "sql", "item_basic.sql"), encoding="utf-8", errors="replace"):
        m = rx.match(line)
        if m:
            basic[int(m.group(1))] = m.group(2)
    lines = ["-- Generated by FFXISOLO\\crowds\\bots\\build_trade_names.py: item names for bot shouts (bots_trade.lua).",
             "return {"]
    n = 0
    for i in sorted(set(ids)):
        name = names.get(i) or (nice(basic[i]) if i in basic else None)
        if name and all(32 <= ord(ch) < 127 for ch in name):
            lines.append("    [%d] = %s," % (i, lua_str(name)))
            n += 1
    lines.append("}")
    out = os.path.join(lua, "bots_trade_names.lua")
    with open(out + ".tmp", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(out + ".tmp", out)
    print("wrote %d names to %s" % (n, out))


if __name__ == "__main__":
    main()

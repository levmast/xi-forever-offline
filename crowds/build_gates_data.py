#!/usr/bin/env python3
"""Builds modules/custom/lua/gates_data.lua for XI: Forever Offline (crowds.lua, bots_gates.lua).

Reads every data/zones/<zone>/zone.yaml of the server (the zone lines the game itself uses) and writes, per area,
its gates: where you walk to leave it, where that takes you, and where you arrive there. A zone line that leads
back into the same area is a Mog House door.

    py build_gates_data.py [--server C:\\ffxi-local\\server] [--out <file>]
"""
import argparse
import math
import os
import sys

import yaml


def load_zone_ids(server):
    with open(os.path.join(server, "data", "enums", "zone.yaml"), encoding="utf-8") as f:
        doc = yaml.safe_load(f)
    return {str(k): int(v) for k, v in (doc.get("values") or {}).items()}


def rot_byte(radians):
    return int(round(float(radians) / (2 * math.pi) * 256)) % 256


def build(server):
    ids = load_zone_ids(server)
    zones_dir = os.path.join(server, "data", "zones")
    gates, skipped = {}, []
    for folder in sorted(os.listdir(zones_dir)):
        path = os.path.join(zones_dir, folder, "zone.yaml")
        if not os.path.isfile(path) or folder not in ids:
            continue
        try:
            with open(path, encoding="utf-8") as f:
                doc = yaml.safe_load(f) or {}
        except Exception as e:  # a zone file that does not parse is left out, not fatal
            skipped.append("%s: %s" % (folder, e))
            continue
        lines = doc.get("zonelines") or {}
        out = []
        for key in sorted(lines):
            ln = lines[key] or {}
            frm, to, at = ln.get("from"), ln.get("to"), ln.get("at")
            if not (isinstance(frm, list) and len(frm) >= 3 and isinstance(at, list) and len(at) >= 3):
                continue
            if to not in ids:
                skipped.append("%s/%s: unknown area %r" % (folder, key, to))
                continue
            out.append({
                "to": ids[to],
                "x": float(frm[0]), "y": float(frm[1]), "z": float(frm[2]),
                "ax": float(at[0]), "ay": float(at[1]), "az": float(at[2]),
                "arot": rot_byte(at[3]) if len(at) >= 4 else 0,
            })
        if out:
            gates[ids[folder]] = (folder, out)

    # the spot just inside each gate: where you stand after coming in through it from the other side (the arrival
    # point of the line back that lies nearest to it). The zone line itself is mostly off the walking map; this is on it.
    for zone_id, (_folder, out) in gates.items():
        for g in out:
            if g["to"] == zone_id:  # a Mog House door: you come out where its own line puts you
                g["px"], g["py"], g["pz"] = g["ax"], g["ay"], g["az"]
                continue
            back = [b for b in gates.get(g["to"], ("", []))[1] if b["to"] == zone_id]
            if back:
                b = min(back, key=lambda b: (b["ax"] - g["x"]) ** 2 + (b["az"] - g["z"]) ** 2)
                g["px"], g["py"], g["pz"] = b["ax"], b["ay"], b["az"]
    return gates, skipped


def write(gates, out_path):
    lines = [
        "-- Generated by build_gates_data.py from the server's own data/zones/*/zone.yaml (zone lines).",
        "-- Do not edit by hand: run the script again instead. Read by crowds.lua and bots_gates.lua.",
        "-- d.gates[area id] = { { to = area id, x, y, z = the zone line in this area (walk here to leave),",
        "--                        ax, ay, az, arot = where you arrive in `to`,",
        "--                        px, py, pz = the spot just inside this gate, on the walking map (where someone coming",
        "--                        in through it stands; absent when no line leads back) }, ... }",
        "-- to == this area: a Mog House door.",
        "local d = {}",
        "d.gates = {",
    ]
    total = 0
    for zone_id in sorted(gates):
        folder, out = gates[zone_id]
        lines.append("    [%d] = { -- %s" % (zone_id, folder))
        for g in out:
            total += 1
            inside = ", px = %.3f, py = %.3f, pz = %.3f" % (g["px"], g["py"], g["pz"]) if "px" in g else ""
            lines.append(
                "        { to = %d, x = %.3f, y = %.3f, z = %.3f, ax = %.3f, ay = %.3f, az = %.3f, arot = %d%s },"
                % (g["to"], g["x"], g["y"], g["z"], g["ax"], g["ay"], g["az"], g["arot"], inside))
        lines.append("    },")
    lines.append("}")
    lines.append("return d")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", default=r"C:\ffxi-local\server")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    out = a.out or os.path.join(a.server, "modules", "custom", "lua", "gates_data.lua")
    gates, skipped = build(a.server)
    total = write(gates, out)
    print("%d areas, %d zone lines -> %s" % (len(gates), total, out))
    for s in skipped[:20]:
        print("  skipped", s)
    if len(skipped) > 20:
        print("  ... and %d more" % (len(skipped) - 20))
    return 0


if __name__ == "__main__":
    sys.exit(main())
